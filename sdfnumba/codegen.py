"""Generated code: one straight-line function per shape.

The interpreter (interp.py) handles any shape immediately but pays for a
dispatch on every instruction.  For a given shape, this module writes the
instructions out as plain code instead:

    def run(code, P, x, y, z, ps, ds, aux):
        sx0, sy0, sz0 = x, y, z
        x, y, z = translate(x, y, z, P, 0)
        d0 = sphere(x, y, z, P, 3)
        x, y, z = sx0, sy0, sz0
        d1 = box(x, y, z, P, 4)
        d0 = union(d0, d1, P, 7)
        return d0

Parameter *offsets* are baked in, parameter *values* are not, so dragging a
slider never needs a recompile; only changing the shape's structure does.

Compiling takes a few seconds, so it happens in a separate process and the
interpreter is used until it is done.  The machine code goes into numba's
cache, so loading it afterwards (in this session or any later one) is quick.

    functions(program)          best available (run, run_id), starting a
                                background compile if needed
    compile(program)            compile now and wait
    enabled = False             always use the interpreter
"""

import os
import subprocess
import sys
import threading

from . import interp, ops
from .ops import PRIM, XFORM, XFORM_AUX, DUNARY, DUNARY_AUX, DBINARY, PUSHP, POPP

enabled = os.environ.get('SDFNUMBA_CODEGEN', '1') != '0'

_KINDS = {op.code: op for op in ops.REGISTRY.values()}


def _body(code, with_ids):
    """Straight-line statements for one program, tracking stack depths
    at generation time so every stack slot becomes a named local."""
    lines = []
    pt = dt = at = 0
    for i, (c, o) in enumerate(code):
        c, o = int(c), int(o)
        if c == PUSHP:
            lines.append(f'sx{pt}, sy{pt}, sz{pt} = x, y, z')
            pt += 1
            continue
        if c == POPP:
            pt -= 1
            lines.append(f'x, y, z = sx{pt}, sy{pt}, sz{pt}')
            continue
        op = _KINDS[c]
        f = op.name
        if op.kind == PRIM:
            lines.append(f'd{dt} = {f}(x, y, z, P, {o})')
            if with_ids:
                lines.append(f'i{dt} = {i}')
            dt += 1
        elif op.kind == XFORM:
            lines.append(f'x, y, z = {f}(x, y, z, P, {o})')
        elif op.kind == XFORM_AUX:
            lines.append(f'x, y, z, a{at} = {f}(x, y, z, P, {o})')
            at += 1
        elif op.kind == DUNARY:
            lines.append(f'd{dt - 1} = {f}(d{dt - 1}, P, {o})')
        elif op.kind == DUNARY_AUX:
            at -= 1
            lines.append(f'd{dt - 1} = {f}(d{dt - 1}, a{at}, P, {o})')
        elif op.kind == DBINARY:
            dt -= 1
            a, b = dt - 1, dt
            if with_ids:
                lines.append(f'if not {op.winner}(d{a}, d{b}, P, {o}):')
                lines.append(f'    i{a} = i{b}')
            lines.append(f'd{a} = {f}(d{a}, d{b}, P, {o})')
    lines.append('return i0' if with_ids else 'return d0')
    return lines


def shape_source(program):
    code = program.code
    out = [
        '# Generated by sdfnumba/codegen.py for one shape. Do not edit.',
        'from numba import njit',
        'from sdfnumba.sigs import RUN, RUN_ID',
        interp.op_imports(),
        '',
        '',
        '@njit(RUN, cache=True, fastmath=True)',
        'def run(code, P, x, y, z, ps, ds, aux):',
    ]
    out += [f'    {s}' for s in _body(code, False)]
    out += ['', '', '@njit(RUN_ID, cache=True, fastmath=True)',
            'def run_id(code, P, x, y, z, ps, ds, aux, ids):']
    out += [f'    {s}' for s in _body(code, True)]
    # the op registry is part of what the code means: tie the file name to it
    out += ['', f'# registry: {interp._module.__name__}', '']
    return '\n'.join(out)


# --- compiling ---------------------------------------------------------------

_jobs = {}          # program key -> _Job
_lock = threading.Lock()


class _Job:
    def __init__(self, name, path):
        self.name, self.path = name, path
        self.proc = None
        self.thread = None
        self.module = None
        self.failed = False

    @property
    def marker(self):
        return f'{self.path}.ok'

    def start(self):
        if os.path.exists(self.marker):       # compiled in an earlier session
            self.load()
            return
        paths = [p for p in sys.path if p]
        script = (f'import sys; sys.path[:0] = {paths!r}\n'
                  f'from sdfnumba.interp import import_path\n'
                  f'import_path({self.name!r}, {self.path!r})\n'
                  f'open({self.marker!r}, "w").close()\n')
        try:
            self.proc = subprocess.Popen([sys.executable, '-c', script],
                                         stdout=subprocess.DEVNULL,
                                         stderr=subprocess.DEVNULL)
        except OSError:
            # no usable interpreter executable: compile on a thread instead
            self.thread = threading.Thread(target=self._compile_here, daemon=True)
            self.thread.start()

    def _compile_here(self):
        try:
            self.load()
            open(self.marker, 'w').close()
        except Exception:
            self.failed = True

    def poll(self):
        if self.module is not None or self.failed:
            return
        if self.proc is not None and self.proc.poll() is not None:
            if self.proc.returncode == 0 and os.path.exists(self.marker):
                self.load()
            else:
                self.failed = True

    def load(self):
        self.module = interp.import_path(self.name, self.path)

    def wait(self):
        if self.proc is not None:
            self.proc.wait()
        if self.thread is not None:
            self.thread.join()
        self.poll()
        if self.module is None and not self.failed:
            self.load()


def _job(program):
    with _lock:
        job = _jobs.get(program.key)
        if job is None:
            name, path = interp.write_generated(shape_source(program), 'shape')
            job = _jobs[program.key] = _Job(name, path)
            job.start()
        return job


def functions(program):
    """(run, run_id) for this program: generated code once it is compiled,
    the interpreter until then (or always, if codegen is disabled)."""
    if enabled:
        job = _job(program)
        job.poll()
        if job.module is not None:
            return job.module.run, job.module.run_id
    return interp.run, interp.run_id


def compile(program):
    """Compile this program's generated code now, waiting for it."""
    job = _job(program)
    job.wait()
    if job.module is None:
        raise RuntimeError('code generation failed for this shape')
    return job.module.run, job.module.run_id


def ready(program):
    if not enabled:
        return False
    job = _job(program)
    job.poll()
    return job.module is not None
