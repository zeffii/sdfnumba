"""The bytecode interpreter.

A compiled shape is two arrays:

    code   int64 (n, 2)   one row per instruction: (opcode, param offset)
    P      float64 (m,)   every parameter, flat

The interpreter keeps the current point in x, y, z and three small stacks:
saved points (PUSHP / POPP), distances, and aux values (see ops.py).

Two functions are made, both with the shared signatures in sigs.py:

    run     -> distance
    run_id  -> index (row in `code`) of the primitive that won at the point

The dispatch loops are written out from the op registry in ops.py, so adding
an op never means editing this file.  The generated source is plain Python
saved in the cache folder (interp_<hash>.py) and can be read like any other
module.  It is compiled once; numba caches the machine code across sessions.
"""

import hashlib
import importlib.util
import os
import sys

from . import ops
from .ops import (PRIM, XFORM, XFORM_AUX, DUNARY, DUNARY_AUX, DBINARY,
                  PUSHP, POPP)

STACK_DEPTH = 64   # limit on nesting depth of a shape tree


def cache_dir():
    path = os.environ.get('SDFNUMBA_CACHE') or os.path.join(
        os.path.expanduser('~'), '.cache', 'sdfnumba')
    os.makedirs(path, exist_ok=True)
    return path


def _branch(op, with_ids):
    """The body of one `elif` in the interpreter loop."""
    f = op.name
    if op.kind == PRIM:
        lines = [f'ds[dt] = {f}(x, y, z, P, o)']
        if with_ids:
            lines.append('ids[dt] = i')
        return lines + ['dt += 1']
    if op.kind == XFORM:
        return [f'x, y, z = {f}(x, y, z, P, o)']
    if op.kind == XFORM_AUX:
        return [f'x, y, z, a = {f}(x, y, z, P, o)', 'aux[at] = a', 'at += 1']
    if op.kind == DUNARY:
        return [f'ds[dt - 1] = {f}(ds[dt - 1], P, o)']
    if op.kind == DUNARY_AUX:
        return ['at -= 1', f'ds[dt - 1] = {f}(ds[dt - 1], aux[at], P, o)']
    if op.kind == DBINARY:
        lines = ['dt -= 1']
        if with_ids:
            lines += [f'if not {op.winner}(ds[dt - 1], ds[dt], P, o):',
                      '    ids[dt - 1] = ids[dt]']
        return lines + [f'ds[dt - 1] = {f}(ds[dt - 1], ds[dt], P, o)']
    raise ValueError(f'unknown op kind for {f}')


def _function(name, signature, with_ids):
    args = 'code, P, x, y, z, ps, ds, aux' + (', ids' if with_ids else '')
    lines = [
        f'@njit({signature}, cache=True, fastmath=True)',
        f'def {name}({args}):',
        '    pt = 0',
        '    dt = 0',
        '    at = 0',
        '    for i in range(code.shape[0]):',
        '        c = code[i, 0]',
        '        o = code[i, 1]',
        f'        if c == {PUSHP}:',
        '            ps[pt, 0] = x',
        '            ps[pt, 1] = y',
        '            ps[pt, 2] = z',
        '            pt += 1',
        f'        elif c == {POPP}:',
        '            pt -= 1',
        '            x = ps[pt, 0]',
        '            y = ps[pt, 1]',
        '            z = ps[pt, 2]',
    ]
    for op in ops.REGISTRY.values():
        lines.append(f'        elif c == {op.code}:  # {op.name}')
        lines += [f'            {s}' for s in _branch(op, with_ids)]
    lines.append('    return ids[0]' if with_ids else '    return ds[0]')
    return lines


def op_imports():
    names = list(ops.REGISTRY) + sorted({op.winner for op in ops.REGISTRY.values()
                                         if op.winner})
    return f'from sdfnumba.ops import {", ".join(names)}'


def interpreter_source():
    lines = [
        '# Generated by sdfnumba/interp.py from the op registry. Do not edit.',
        'from numba import njit',
        'from sdfnumba.sigs import RUN, RUN_ID',
        op_imports(),
        '',
        '',
    ]
    lines += _function('run', 'RUN', False)
    lines += ['', '']
    lines += _function('run_id', 'RUN_ID', True)
    return '\n'.join(lines) + '\n'


def generated_path(source, stem):
    digest = hashlib.sha1(source.encode()).hexdigest()[:12]
    name = f'{stem}_{digest}'
    return name, os.path.join(cache_dir(), f'{name}.py')


def write_generated(source, stem):
    """Write `source` to the cache folder unless it is already there."""
    name, path = generated_path(source, stem)
    if not os.path.exists(path):
        tmp = f'{path}.{os.getpid()}.tmp'
        with open(tmp, 'w') as fh:
            fh.write(source)
        os.replace(tmp, path)
    return name, path


def import_path(name, path):
    if name in sys.modules:
        return sys.modules[name]
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module   # numba's cache looks modules up by name
    spec.loader.exec_module(module)
    return module


def load_generated(source, stem):
    return import_path(*write_generated(source, stem))


_module = load_generated(interpreter_source(), 'interp')
run = _module.run
run_id = _module.run_id
