"""The bytecode interpreter.

A compiled shape is two arrays:

    code   int64 (n, 2)   one row per instruction: (opcode, param offset)
    P      float64 (m,)   every parameter, flat

The interpreter keeps the current point in x, y, z and three small stacks:
saved points (PUSHP / POPP), distances, and aux values (see ops.py).

The dispatch loop is written out from the op registry in ops.py, so adding an
op never means editing this file.  The generated source is plain Python saved
in the cache folder (interp_<hash>.py) and can be read like any other module.
It is compiled once; numba caches the machine code across sessions.
"""

import hashlib
import importlib.util
import os
import sys

from . import ops
from .ops import (PRIM, XFORM, XFORM_AUX, DUNARY, DUNARY_AUX, DBINARY,
                  PUSHP, POPP)

STACK_DEPTH = 64   # limit on nesting depth of a shape tree


def cache_dir():
    path = os.environ.get('SDFNUMBA_CACHE') or os.path.join(
        os.path.expanduser('~'), '.cache', 'sdfnumba')
    os.makedirs(path, exist_ok=True)
    return path


def _dispatch_branch(op):
    """The body of one `elif` in the interpreter loop."""
    f = op.name
    if op.kind == PRIM:
        return [f'ds[dt] = {f}(x, y, z, P, o)', 'dt += 1']
    if op.kind == XFORM:
        return [f'x, y, z = {f}(x, y, z, P, o)']
    if op.kind == XFORM_AUX:
        return [f'x, y, z, a = {f}(x, y, z, P, o)', 'aux[at] = a', 'at += 1']
    if op.kind == DUNARY:
        return [f'ds[dt - 1] = {f}(ds[dt - 1], P, o)']
    if op.kind == DUNARY_AUX:
        return ['at -= 1', f'ds[dt - 1] = {f}(ds[dt - 1], aux[at], P, o)']
    if op.kind == DBINARY:
        return ['dt -= 1', f'ds[dt - 1] = {f}(ds[dt - 1], ds[dt], P, o)']
    raise ValueError(f'unknown op kind for {f}')


def interpreter_source():
    names = ', '.join(ops.REGISTRY)
    lines = [
        '# Generated by sdfnumba/interp.py from the op registry. Do not edit.',
        'from numba import njit',
        f'from sdfnumba.ops import {names}',
        '',
        '',
        '@njit(cache=True, fastmath=True)',
        'def run(code, P, x, y, z, ps, ds, aux):',
        '    pt = 0',
        '    dt = 0',
        '    at = 0',
        '    for i in range(code.shape[0]):',
        '        c = code[i, 0]',
        '        o = code[i, 1]',
        f'        if c == {PUSHP}:',
        '            ps[pt, 0] = x',
        '            ps[pt, 1] = y',
        '            ps[pt, 2] = z',
        '            pt += 1',
        f'        elif c == {POPP}:',
        '            pt -= 1',
        '            x = ps[pt, 0]',
        '            y = ps[pt, 1]',
        '            z = ps[pt, 2]',
    ]
    for op in ops.REGISTRY.values():
        lines.append(f'        elif c == {op.code}:  # {op.name}')
        lines += [f'            {s}' for s in _dispatch_branch(op)]
    lines += ['    return ds[0]', '']
    return '\n'.join(lines)


def load_generated(source, stem):
    """Write `source` to the cache folder (if changed) and import it."""
    digest = hashlib.sha1(source.encode()).hexdigest()[:12]
    name = f'{stem}_{digest}'
    path = os.path.join(cache_dir(), f'{name}.py')
    if not os.path.exists(path):
        tmp = f'{path}.{os.getpid()}.tmp'
        with open(tmp, 'w') as fh:
            fh.write(source)
        os.replace(tmp, path)
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module   # numba's cache looks modules up by name
    spec.loader.exec_module(module)
    return module


run = load_generated(interpreter_source(), 'interp').run
